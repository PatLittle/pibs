const { chromium } = require('playwright');
const fs = require('fs');
const assert = require('node:assert/strict');
(async () => {
 const browser = await chromium.launch({headless:true,executablePath:process.env.BROWSER_EXECUTABLE || (fs.existsSync('/usr/bin/chromium') ? '/usr/bin/chromium' : undefined),args:['--no-sandbox']});
 const page = await browser.newPage({viewport:{width:1440,height:1100}});
 const errors=[]; page.on('pageerror',e=>errors.push(e.message));
 const base=process.env.PIA_TEST_BASE || 'http://127.0.0.1:8765/';
 const data=JSON.parse(fs.readFileSync('site/data/privacy_assessments.json','utf8'));
 await page.goto(base+'index.html');
 await page.waitForFunction(()=>document.querySelector('gcds-header').getBoundingClientRect().height>100,{},{timeout:30000});
 await page.locator('gcds-top-nav gcds-nav-link[href="privacy-assessments.html"]').click();
 await page.waitForFunction(()=>document.getElementById('stat-assessments').textContent==='417');
 await page.waitForFunction(()=>document.querySelector('gcds-header').getBoundingClientRect().height>100,{},{timeout:30000});
 assert.equal(await page.locator('#assessment-rows tr').count(),25);
 await page.screenshot({path:'work/pia-home-desktop.png',fullPage:false});
 const dept='ati-schedule-i-office-of-the-superintendent-of-financial-institutions';
 await page.selectOption('#department',dept);
 assert.equal(await page.locator('#assessment-rows tr').count(),5);
 assert.ok((await page.locator('#assessment-status').textContent()).startsWith('5 of'));
 await page.locator('#assessment-search').fill('zzzz-no-record');
 assert.ok((await page.locator('#assessment-status').textContent()).includes('No assessments'));
 await page.locator('#clear-filters').click();
 await page.locator('#page-next').click(); assert.ok((await page.locator('#page-summary').textContent()).startsWith('Page 2'));
 await page.selectOption('#department',dept);
 assert.equal(await page.locator('#page-summary').textContent(),'Page 1 of 1');
 await page.locator('#assessment-rows .button-link').first().click();
 await page.waitForSelector('#document-body:not([hidden])');
 assert.equal(await page.locator('h1').count(),1);
 assert.ok((await page.locator('#document-body').textContent()).includes('September 2025'));
 assert.ok(await page.locator('#document-language').isVisible());
 await page.locator('#language-fr').click();
 assert.equal(await page.locator('#document-body').getAttribute('lang'),'fr');
 assert.equal(await page.locator('#language-fr').getAttribute('aria-pressed'),'true');
 assert.ok(page.url().includes('lang=fr'));
 await page.screenshot({path:'work/pia-reader-desktop.png',fullPage:true});
 await page.goBack();
 assert.equal(await page.locator('#document-body').getAttribute('lang'),'en');
 await page.locator('#back-to-assessments').click();
 await page.waitForSelector('#assessment-rows .button-link');
 assert.equal(await page.locator('#department').inputValue(),dept);
 await page.locator('#clear-filters').click();
 await page.selectOption('#availability','none');
 const count=data.records.filter(r=>!r.available_languages.length).length;
 assert.ok((await page.locator('#assessment-status').textContent()).startsWith(count+' of'));
 await page.locator('#assessment-rows .button-link').first().click();
 await page.waitForSelector('#reader-content:not([hidden])');
 assert.ok(await page.locator('#language-availability-notice').isVisible());
 assert.ok(await page.locator('#document-body').isHidden());
 assert.ok(await page.locator('#original-source').isVisible());
 const unavailable=data.records.find(r=>!r.available_languages.length);
 if(!unavailable.sources.en && unavailable.sources.fr) assert.equal(await page.locator('#assessment-title').getAttribute('lang'),'fr');
 await page.goto(base+'privacy-assessment.html?institution_id=not-a-department&pia_id=not-an-id');
 await page.waitForFunction(()=>document.getElementById('assessment-title').textContent==='Assessment not found');
 // A fetched PDF is represented by its converted Markdown in the same reader.
 const pdf=data.records.find(r=>Object.values(r.sources).some(s=>s.url.includes('.pdf')) && r.available_languages.length===2);
 await page.goto(base+`privacy-assessment.html?institution_id=${pdf.institution_id}&pia_id=${pdf.pia_id}`);
 await page.waitForSelector('#document-body:not([hidden])');
 assert.ok((await page.locator('#document-body').textContent()).length>300);
 const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
 mobile.on('pageerror',e=>errors.push(e.message));
 await mobile.goto(base+'privacy-assessments.html');
 await mobile.waitForFunction(()=>document.getElementById('stat-assessments').textContent==='417');
 await mobile.waitForFunction(()=>document.querySelector('gcds-header').getBoundingClientRect().height>100,{},{timeout:30000});
 await mobile.screenshot({path:'work/pia-home-mobile.png',fullPage:true});
 assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1),true,'Mobile page overflows');
 await mobile.selectOption('#department',dept);
 await mobile.locator('#assessment-rows .button-link').first().click();
 await mobile.waitForSelector('#document-body:not([hidden])');
 await mobile.locator('#language-fr').click();
 await mobile.screenshot({path:'work/pia-reader-mobile.png',fullPage:true});
 assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1),true,'Mobile reader overflows');
 const failure=await browser.newPage();
 await failure.route('**/data/privacy_assessments.json',route=>route.fulfill({status:500,body:'unavailable'}));
 await failure.goto(base+'privacy-assessments.html');
 await failure.waitForSelector('#assessment-status[role="alert"]');
 assert.deepEqual(errors,[]);
 console.log(JSON.stringify({desktop:'passed',mobile:'passed',filtering:'passed',pagination:'passed',bilingualReader:'passed',inlineAndPdf:'passed',unavailableAndInvalid:'passed',networkFailure:'passed',pageErrors:errors},null,2));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
